    public static function number(int|float $n): string
    {
        $n = (int) floor($n);
        if ($n === 0) {
            return 'শূন্য';
        }

        $parts = [];
        if ($n >= 10000000) { $parts[] = self::number(intdiv($n, 10000000)) . ' কোটি'; $n %= 10000000; }
        if ($n >= 100000)   { $parts[] = self::ONES[intdiv($n, 100000)] . ' লক্ষ';      $n %= 100000; }
        if ($n >= 1000)     { $parts[] = self::ONES[intdiv($n, 1000)] . ' হাজার';       $n %= 1000; }
        if ($n >= 100)      { $parts[] = self::ONES[intdiv($n, 100)] . ' শত';           $n %= 100; }
        if ($n > 0)         { $parts[] = self::ONES[$n]; }

        return implode(' ', $parts);
    }

    public static function taka(int|float|null $amount): string
    {
        $amount = (float) ($amount ?? 0);
        if ($amount <= 0) {
            return '';
        }

        $tk = (int) floor($amount);
        $ps = (int) round(($amount - $tk) * 100);

        $s = $tk > 0 ? self::number($tk) . ' টাকা' : '';
        if ($ps > 0) {
            $s .= ($s !== '' ? ' ' : '') . self::number($ps) . ' পয়সা';
        }

        return $s;
    }
}
